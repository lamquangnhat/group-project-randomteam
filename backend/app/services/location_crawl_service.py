import httpx
import uuid
from sqlalchemy.orm import Session
from app.models.location import Location
from datetime import datetime


# ─── Wikipedia ───────────────────────────────────────────────────────────────

async def fetch_wikipedia_data(place_name: str) -> dict:
    """Fetch description and image — uses fallback data if API is blocked."""
    
    # Check fallback data first
    key = place_name.lower().strip()
    if key in FALLBACK_DATA:
        return FALLBACK_DATA[key]

    # Try Wikipedia API
    url = f"https://en.wikipedia.org/api/rest_v1/page/summary/{place_name.replace(' ', '_')}"
    async with httpx.AsyncClient() as client:
        try:
            response = await client.get(url, timeout=10)
            if response.status_code == 200:
                data = response.json()
                description = data.get("extract", "")
                image_url = data.get("thumbnail", {}).get("source", None)
                if description and len(description) > 50:
                    return {"description": description, "image_url": image_url}
        except Exception:
            pass

    return {"description": "", "image_url": None}

# ─── OpenStreetMap Nominatim ──────────────────────────────────────────────────

async def fetch_osm_data(place_name: str, country: str = "") -> dict:
    """Fetch coordinates, address, city, country from OpenStreetMap."""
    query = f"{place_name}, {country}" if country else place_name
    url = "https://nominatim.openstreetmap.org/search"
    params = {
        "q": query,
        "format": "json",
        "limit": 1,
        "addressdetails": 1,
    }
    headers = {
        # OSM requires a User-Agent identifying your app
        "User-Agent": "TravelPlannerCollegeProject/1.0"
    }

    async with httpx.AsyncClient() as client:
        try:
            response = await client.get(url, params=params, headers=headers, timeout=10)
            if response.status_code == 200:
                results = response.json()
                if results:
                    result = results[0]
                    address = result.get("address", {})
                    return {
                        "latitude": float(result.get("lat", 0)),
                        "longitude": float(result.get("lon", 0)),
                        "address": result.get("display_name", ""),
                        "city": (
                            address.get("city")
                            or address.get("town")
                            or address.get("state", "")
                        ),
                        "country": address.get("country", ""),
                    }
        except Exception:
            pass
    return {"latitude": 0.0, "longitude": 0.0, "address": "", "city": "", "country": ""}


# ─── Main Crawl Function ──────────────────────────────────────────────────────

async def crawl_and_save_location(
    place_name: str,
    category: str,
    db: Session,
    country: str = "",
) -> dict:
    """
    Crawl Wikipedia + OSM for a place, save to DB if not already exists.
    Returns the saved location dict.
    """

    # 1. Check if location already exists
    existing = db.query(Location).filter(Location.name == place_name).first()
    if existing:
        return {"status": "skipped", "message": f"'{place_name}' already exists.", "location": _to_dict(existing)}

    # 2. Fetch from both APIs concurrently
    wiki_data = await fetch_wikipedia_data(place_name)
    osm_data = await fetch_osm_data(place_name, country)

    # 3. Build and save the Location object
    location = Location(
        id=uuid.uuid4(),
        name=place_name,
        description=wiki_data["description"],
        address=osm_data["address"],
        city=osm_data["city"],
        country=osm_data["country"] or country,
        latitude=osm_data["latitude"],
        longitude=osm_data["longitude"],
        category=category,
        avg_rating=0,
        total_reviews=0,
        created_at=datetime.utcnow(),
    )

    db.add(location)
    db.commit()
    db.refresh(location)

    return {"status": "created", "message": f"'{place_name}' saved successfully.", "location": _to_dict(location)}


async def crawl_bulk_locations(places: list[dict], db: Session) -> list[dict]:
    """
    Crawl multiple locations at once.
    Each item in places: { "name": str, "category": str, "country": str (optional) }
    """
    results = []
    for place in places:
        result = await crawl_and_save_location(
            place_name=place["name"],
            category=place.get("category", "general"),
            db=db,
            country=place.get("country", ""),
        )
        results.append(result)
    return results


# ─── Helper ───────────────────────────────────────────────────────────────────

def _to_dict(location: Location) -> dict:
    return {
        "id": str(location.id),
        "name": location.name,
        "description": location.description,
        "address": location.address,
        "city": location.city,
        "country": location.country,
        "latitude": location.latitude,
        "longitude": location.longitude,
        "category": location.category,
        "avg_rating": location.avg_rating,
        "total_reviews": location.total_reviews,
    }